"""Command-Line Interface (CLI) for running the Maze Search Benchmark Suite.

Academic Integrity Notice:
All numbers presented in reports, posters, slides, and README must come strictly
from the output files generated by executing this script on the actual machine.
"""

from __future__ import annotations
import argparse
import sys
from pathlib import Path

# Add project root to sys.path
sys.path.insert(0, str(Path(__file__).resolve().parent))

from src.maze_agent.maze_library import get_predefined_mazes
from src.maze_agent.algorithms import ALGORITHMS
from src.maze_agent.evaluation.benchmark import run_benchmark_suite
from src.maze_agent.evaluation.export import (
    export_to_csv,
    export_to_json,
    save_comparison_charts,
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Run fair empirical benchmarks comparing BFS, DFS, IDS, and A*."
    )
    parser.add_argument(
        "--repetitions",
        "-n",
        type=int,
        default=10,
        help="Number of timed repetitions per algorithm-maze combination (default: 10).",
    )
    parser.add_argument(
        "--output-dir",
        "-o",
        type=str,
        default="results",
        help="Directory to save CSV, JSON, and PNG chart results (default: 'results').",
    )
    parser.add_argument(
        "--mazes",
        type=str,
        default="all",
        help="Comma-separated maze names or 'all' (default: 'all').",
    )
    parser.add_argument(
        "--algorithms",
        type=str,
        default="all",
        help="Comma-separated algorithm names ('BFS,DFS,IDS,A*') or 'all' (default: 'all').",
    )
    parser.add_argument(
        "--no-memory",
        action="store_true",
        help="Skip tracemalloc memory profiling.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    all_mazes = get_predefined_mazes()
    if args.mazes.lower() == "all":
        selected_mazes = all_mazes
    else:
        req_names = [name.strip() for name in args.mazes.split(",") if name.strip()]
        selected_mazes = {
            name: all_mazes[name] for name in req_names if name in all_mazes
        }
        if not selected_mazes:
            print(f"Error: None of the requested mazes {req_names} exist.")
            print(f"Available mazes: {list(all_mazes.keys())}")
            sys.exit(1)

    if args.algorithms.lower() == "all":
        selected_algos = list(ALGORITHMS.keys())
    else:
        selected_algos = [
            a.strip() for a in args.algorithms.split(",") if a.strip() in ALGORITHMS
        ]
        if not selected_algos:
            print("Error: No valid algorithms specified.")
            print(f"Available algorithms: {list(ALGORITHMS.keys())}")
            sys.exit(1)

    print("======================================================================")
    print("           MAZE-SOLVING AGENT EMPIRICAL BENCHMARK SUITE               ")
    print("======================================================================")
    print(f"Mazes to test: {list(selected_mazes.keys())}")
    print(f"Algorithms:    {selected_algos}")
    print(f"Repetitions:   {args.repetitions} timed runs (+ 1 warm-up)")
    print(f"Peak Memory:   {'Disabled' if args.no_memory else 'Enabled (isolated tracemalloc pass)'}")
    print(f"Output folder: {output_dir.resolve()}")
    print("----------------------------------------------------------------------")
    print("Executing benchmark runs... please wait.")

    benchmark_data = run_benchmark_suite(
        mazes=selected_mazes,
        algorithms=selected_algos,
        repetitions=args.repetitions,
        measure_memory=not args.no_memory,
    )

    results_list = benchmark_data["results"]

    # Export to disk
    csv_file = output_dir / "benchmark_results.csv"
    json_file = output_dir / "benchmark_results.json"
    png_file = output_dir / "comparison_charts.png"

    export_to_csv(results_list, csv_file)
    export_to_json(benchmark_data, json_file)
    save_comparison_charts(results_list, png_file)

    print("----------------------------------------------------------------------")
    print("Benchmark completed successfully! Real experimental data saved to:")
    print(f"  - CSV:   {csv_file}")
    print(f"  - JSON:  {json_file}")
    print(f"  - Chart: {png_file}")
    print("======================================================================")
    print("                     SUMMARY OF MEASURED RESULTS                      ")
    print("======================================================================")
    header = f"{'Maze':<18} | {'Algo':<5} | {'Found':<5} | {'Path (moves)':<12} | {'Expanded':<8} | {'Median ms':<10} | {'Peak KB':<8}"
    print(header)
    print("-" * len(header))

    for r in results_list:
        path_str = str(r["path_length"]) if r["found"] else "No Path"
        mem_kb = (r["peak_memory_bytes"] / 1024.0) if r.get("peak_memory_bytes") else 0.0
        print(
            f"{r['maze_name']:<18} | {r['algorithm']:<5} | {str(r['found']):<5} | "
            f"{path_str:<12} | {r['nodes_expanded']:<8} | {r['time_median_ms']:<10.3f} | {mem_kb:<8.1f}"
        )
    print("======================================================================")


if __name__ == "__main__":
    main()
